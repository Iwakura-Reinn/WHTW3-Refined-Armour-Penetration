"""Build refined_armour_penetration_v1.dll, embed into Lua, pack .pack, and deploy."""
import hashlib
import shutil
import struct
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
GAME_DIR = Path(r"d:\SteamLibrary\steamapps\common\Total War WARHAMMER III")
BUILD_DIR = ROOT / "build"
DLL_BUILD = BUILD_DIR / "refined_armour_penetration_v1.dll"
BIN_LUA = ROOT / "lua" / "script" / "_lib" / "mod" / "refined_armour_penetration_bin.lua"
PACK_OUT = Path(r"D:\TW3_Modding\wh3_mod\packs\refined_armour_penetration.pack")
DATA_PACK = GAME_DIR / "data" / "refined_armour_penetration.pack"


def compile_dll():
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        "gcc",
        "-shared",
        "-O2",
        "-Wall",
        "-Wextra",
        "-o",
        str(DLL_BUILD),
        str(ROOT / "src" / "refined_armour_penetration.c"),
        "-lm",
    ]
    print("Compiling:", " ".join(cmd))
    subprocess.run(cmd, check=True)
    print(f"Built DLL: {DLL_BUILD} ({DLL_BUILD.stat().st_size} bytes)")


def generate_embedded_lua():
    raw = DLL_BUILD.read_bytes()
    tag = hashlib.sha256(raw).hexdigest()[:16]
    hex_str = raw.hex()
    # Split into 128-char lines for clean Lua parsing
    chunks = [hex_str[i:i + 128] for i in range(0, len(hex_str), 128)]
    lines = [
        "-- Auto-generated by build.py. Do not edit manually.",
        "return {",
        f"    size = {len(raw)},",
        f'    tag = "{tag}",',
        "    hex = table.concat({",
    ]
    for c in chunks:
        lines.append(f'        "{c}",')
    lines.append("    })")
    lines.append("}")
    BIN_LUA.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Embedded DLL into {BIN_LUA} ({len(raw)} bytes)")


def build_pfh5_pack(pack_path: Path, files: list[tuple[str, bytes]]):
    index_chunks = []
    data_chunks = []
    for rel_path, content in files:
        pbytes = rel_path.replace("/", "\\").encode("utf-8") + b"\x00"
        index_chunks.append(struct.pack("<IB", len(content), 0) + pbytes)
        data_chunks.append(content)

    index_blob = b"".join(index_chunks)
    header = struct.pack(
        "<4sIIIIII",
        b"PFH5",
        3,
        0,
        0,
        len(files),
        len(index_blob),
        int(time.time()),
    )
    pack_path.parent.mkdir(parents=True, exist_ok=True)
    pack_path.write_bytes(header + index_blob + b"".join(data_chunks))
    print(f"Packed: {pack_path} ({pack_path.stat().st_size} bytes, {len(files)} files)")


def main():
    compile_dll()
    generate_embedded_lua()

    lua_root = ROOT / "lua"
    files = []
    for p in sorted(lua_root.rglob("*.lua")):
        rel = str(p.relative_to(lua_root)).replace("/", "\\")
        files.append((rel, p.read_bytes()))

    build_pfh5_pack(PACK_OUT, files)
    shutil.copy2(PACK_OUT, DATA_PACK)
    print(f"Deployed Pack -> {DATA_PACK}")


if __name__ == "__main__":
    main()
